// Package core contains the protocol types shared by the control service and
// clients. It deliberately has no operating-system or transport dependency.
package core

import (
	"encoding/base64"
	"errors"
	"fmt"
	"net/netip"
	"regexp"
	"strings"
	"time"
)

const (
	// ProtocolVersion is incremented when a wire-compatible change is made.
	ProtocolVersion      uint16 = 1
	MaxIDLength                 = 64
	MaxNetworkNameLength        = 128
)

var idPattern = regexp.MustCompile(`^[A-Za-z0-9][A-Za-z0-9._-]{0,63}$`)

// DeviceID and NetworkID are opaque server-assigned identifiers. Keeping them
// as distinct types prevents accidentally using a network ID as a device ID.
type DeviceID string
type NetworkID string

func (id DeviceID) String() string  { return string(id) }
func (id NetworkID) String() string { return string(id) }

func (id DeviceID) Validate() error  { return validateID(string(id), "device ID") }
func (id NetworkID) Validate() error { return validateID(string(id), "network ID") }

func validateID(value, label string) error {
	if !idPattern.MatchString(value) {
		return fmt.Errorf("invalid %s: must be 1-%d ASCII letters, digits, '.', '_' or '-'", label, MaxIDLength)
	}
	return nil
}

// NewDeviceID and NewNetworkID validate caller-provided identifiers. The
// control service can generate IDs independently; these helpers are useful at
// API boundaries where untrusted input is accepted.
func NewDeviceID(value string) (DeviceID, error) {
	id := DeviceID(strings.TrimSpace(value))
	return id, id.Validate()
}

func NewNetworkID(value string) (NetworkID, error) {
	id := NetworkID(strings.TrimSpace(value))
	return id, id.Validate()
}

// DeviceIdentity is the public portion of a device identity. Private keys are
// never sent to or stored by the control service.
type DeviceIdentity struct {
	DeviceID           DeviceID `json:"device_id"`
	WireGuardPublicKey string   `json:"wireguard_public_key"`
	SigningPublicKey   string   `json:"signing_public_key,omitempty"`
}

func (i DeviceIdentity) Validate() error {
	if err := i.DeviceID.Validate(); err != nil {
		return err
	}
	if err := ValidateWireGuardPublicKey(i.WireGuardPublicKey); err != nil {
		return fmt.Errorf("wireguard public key: %w", err)
	}
	if i.SigningPublicKey != "" {
		if err := ValidateEd25519PublicKey(i.SigningPublicKey); err != nil {
			return fmt.Errorf("signing public key: %w", err)
		}
	}
	return nil
}

// ValidateWireGuardPublicKey checks the canonical WireGuard base64 encoding.
// It does not perform a cryptographic operation; key possession is proven by
// the WireGuard handshake in the data-plane adapter.
func ValidateWireGuardPublicKey(value string) error {
	decoded, err := base64.StdEncoding.DecodeString(value)
	if err != nil || len(decoded) != 32 || base64.StdEncoding.EncodeToString(decoded) != value {
		return errors.New("must be canonical base64 encoding of 32 bytes")
	}
	return nil
}

func ValidateEd25519PublicKey(value string) error {
	decoded, err := base64.StdEncoding.DecodeString(value)
	if err != nil || len(decoded) != 32 || base64.StdEncoding.EncodeToString(decoded) != value {
		return errors.New("must be canonical base64 encoding of 32 bytes")
	}
	return nil
}

// Network describes a private overlay network. PasswordHash is an Argon2id
// (or equivalent) verifier generated by the control service; plaintext
// passwords must never be put in this structure.
type Network struct {
	ID           NetworkID `json:"id"`
	Name         string    `json:"name"`
	CIDR         string    `json:"cidr"`
	PasswordHash string    `json:"password_hash,omitempty"`
	CreatedAt    time.Time `json:"created_at"`
	UpdatedAt    time.Time `json:"updated_at"`
}

func (n Network) Validate() error {
	if err := n.ID.Validate(); err != nil {
		return err
	}
	name := strings.TrimSpace(n.Name)
	if name == "" || len(name) > MaxNetworkNameLength {
		return fmt.Errorf("network name must be 1-%d characters", MaxNetworkNameLength)
	}
	prefix, err := netip.ParsePrefix(n.CIDR)
	if err != nil || !prefix.IsValid() || !prefix.Addr().Is4() {
		return errors.New("network CIDR must be a valid IPv4 prefix")
	}
	return nil
}

type MemberRole string

const (
	MemberRoleMember MemberRole = "member"
	MemberRoleAdmin  MemberRole = "admin"
)

type NetworkMember struct {
	NetworkID NetworkID      `json:"network_id"`
	Identity  DeviceIdentity `json:"identity"`
	VirtualIP string         `json:"virtual_ip"`
	Role      MemberRole     `json:"role"`
	Enabled   bool           `json:"enabled"`
	JoinedAt  time.Time      `json:"joined_at"`
}

func (m NetworkMember) Validate() error {
	if err := m.NetworkID.Validate(); err != nil {
		return err
	}
	if err := m.Identity.Validate(); err != nil {
		return err
	}
	ip, err := netip.ParseAddr(m.VirtualIP)
	if err != nil || !ip.Is4() {
		return errors.New("virtual IP must be a valid IPv4 address")
	}
	if m.Role != MemberRoleMember && m.Role != MemberRoleAdmin {
		return errors.New("invalid member role")
	}
	return nil
}

type CandidateKind string
type Transport string

const (
	CandidateHost            CandidateKind = "host"
	CandidateServerReflexive CandidateKind = "srflx"
	CandidateRelay           CandidateKind = "relay"
	TransportUDP             Transport     = "udp"
	TransportTCP             Transport     = "tcp"
)

// Candidate is an authenticated endpoint exchanged through Signal. Address is
// deliberately a string so the control-plane JSON format remains stable.
type Candidate struct {
	Kind      CandidateKind `json:"kind"`
	Transport Transport     `json:"transport"`
	Address   string        `json:"address"`
	Priority  uint32        `json:"priority"`
	Token     string        `json:"token,omitempty"`
}

func (c Candidate) Validate() error {
	if c.Kind != CandidateHost && c.Kind != CandidateServerReflexive && c.Kind != CandidateRelay {
		return errors.New("invalid candidate kind")
	}
	if c.Transport != TransportUDP && c.Transport != TransportTCP {
		return errors.New("invalid candidate transport")
	}
	if c.Address == "" || len(c.Address) > 256 {
		return errors.New("candidate address is required")
	}
	address, err := netip.ParseAddrPort(c.Address)
	if err != nil || address.Port() == 0 || address.Addr().IsUnspecified() || address.Addr().IsMulticast() {
		return errors.New("candidate must contain a unicast IP address and a nonzero port")
	}
	if len(c.Token) > 2048 {
		return errors.New("candidate token exceeds limit")
	}
	if c.Kind == CandidateRelay && c.Token == "" {
		return errors.New("relay candidate requires a token")
	}
	return nil
}

type ConnectionState string

const (
	ConnectionOffline   ConnectionState = "offline"
	ConnectionChecking  ConnectionState = "checking"
	ConnectionDirectUDP ConnectionState = "direct_udp"
	ConnectionDirectTCP ConnectionState = "direct_tcp"
	ConnectionRelayUDP  ConnectionState = "relay_udp"
	ConnectionRelayTCP  ConnectionState = "relay_tcp"
	ConnectionFailed    ConnectionState = "failed"
)

type ConnectivityReport struct {
	PeerID        DeviceID        `json:"peer_id"`
	State         ConnectionState `json:"state"`
	RTTMillis     uint32          `json:"rtt_ms,omitempty"`
	PacketLossPPM uint32          `json:"packet_loss_ppm,omitempty"`
	LastError     string          `json:"last_error,omitempty"`
	CheckedAt     time.Time       `json:"checked_at"`
}

// ACLRule is an ordered rule. The first matching rule wins. Empty protocol or
// port range matches any value. The enforcement package validates addresses and
// performs matching without making assumptions about the transport.
type ACLRule struct {
	ID         string `json:"id"`
	Priority   int    `json:"priority"`
	Action     string `json:"action"` // allow or deny
	SourceCIDR string `json:"source_cidr,omitempty"`
	DestCIDR   string `json:"dest_cidr,omitempty"`
	Protocol   string `json:"protocol,omitempty"` // tcp, udp, icmp
	FromPort   uint16 `json:"from_port,omitempty"`
	ToPort     uint16 `json:"to_port,omitempty"`
}

func (r ACLRule) Validate() error {
	if r.ID == "" || len(r.ID) > MaxIDLength {
		return errors.New("ACL rule ID is required")
	}
	if r.Action != "allow" && r.Action != "deny" {
		return errors.New("ACL action must be allow or deny")
	}
	if r.SourceCIDR != "" {
		if _, err := netip.ParsePrefix(r.SourceCIDR); err != nil {
			return fmt.Errorf("source CIDR: %w", err)
		}
	}
	if r.DestCIDR != "" {
		if _, err := netip.ParsePrefix(r.DestCIDR); err != nil {
			return fmt.Errorf("destination CIDR: %w", err)
		}
	}
	if r.Protocol != "" && r.Protocol != "tcp" && r.Protocol != "udp" && r.Protocol != "icmp" {
		return errors.New("unsupported ACL protocol")
	}
	if r.ToPort != 0 && r.FromPort > r.ToPort {
		return errors.New("ACL port range is reversed")
	}
	return nil
}
